"""Build results/main_table.md and figures/layer_sweep_<dataset>.{pdf,png} from results/*.json only."""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

MODELS = ["llama", "qwen", "gemma"]
ROWS = [("A_linear_probe", "A. Linear probe (hidden state)"),
        ("C_lang_normalised", "C. Probe, language-mean removed"),
        ("baseline_first_token_entropy", "Baseline: first-token entropy"),
        ("baseline_neg_mean_logprob", "Baseline: −mean answer log-prob"),
        ("baseline_answer_length", "Baseline: answer length"),
        ("baseline_metadata", "Baseline: metadata"),
        ("baseline_question_text", "Baseline: question-text embedding")]


def J(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def cell(r, k="auroc"):
    if not r or k not in r:
        return "—"
    lo, hi = r[f"{k}_ci"]
    return f"{r[k]:.3f} [{lo:.3f}, {hi:.3f}]"


def block(out, dataset, target, title):
    R = {m: J(f"results/probes_{m}_{dataset}_{target}.json") for m in MODELS}
    R = {m: r for m, r in R.items() if r}
    if not R:
        return
    for metric in ["auroc", "auprc"]:
        out.append(f"\n### {title} — {metric.upper()} [95% CI, bootstrap over questions]\n")
        out.append("| Method | " + " | ".join(R) + " |")
        out.append("|---|" + "---|" * len(R))
        out.append("| rows / questions / positive rate | " + " | ".join(
            f"{r['n_rows']} / {r['n_groups']} / {r['A_linear_probe']['base_rate']:.2f}" for r in R.values()) + " |")
        for k, name in ROWS:
            out.append(f"| {name} | " + " | ".join(cell(r.get(k), metric) for r in R.values()) + " |")
    if all("B_spread_ridge" in r for r in R.values()):
        out.append("\nB. Spread ridge, Spearman [CI]: " + "; ".join(
            f"{m} {r['B_spread_ridge']['spearman']:.3f} {r['B_spread_ridge']['spearman_ci']}" for m, r in R.items()))
    out.append("\nPaired test, probe A − best baseline (AUROC diff [CI], one-sided bootstrap p): " + "; ".join(
        f"{m}: vs {r['paired_A_vs_best_baseline']['baseline'].replace('baseline_', '')} "
        f"{r['paired_A_vs_best_baseline']['diff']:+.3f} {r['paired_A_vs_best_baseline']['ci']} "
        f"p={r['paired_A_vs_best_baseline']['p_one_sided']}" for m, r in R.items()))
    out.append("\nLayers chosen by inner CV (probe A, per outer fold): " + "; ".join(
        f"{m}: {[c['layer'] for c in r['A_linear_probe']['chosen']]}" for m, r in R.items()))
    for m, r in R.items():
        if "by_dataset" in r:
            out.append(f"\nPooled model {m}, split by dataset: " + "; ".join(
                f"{ds}: " + ", ".join(f"{k.replace('baseline_', '')} {v['auroc']:.3f} {v['auroc_ci']}" for k, v in x.items())
                for ds, x in r["by_dataset"].items()))
    H = {m: r["heldout_language"] for m, r in R.items() if "heldout_language" in r}
    if H:
        out.append("\nHeld-out language (probe A, train without language L and without the test questions):\n")
        langs = sorted({l for h in H.values() for l in h["results"]})
        out.append("| lang | " + " | ".join(f"{m} (layer {h['layer']})" for m, h in H.items()) + " |")
        out.append("|---|" + "---|" * len(H))
        for l in langs:
            out.append(f"| {l} | " + " | ".join(
                (f"{h['results'][l]['auroc']:.3f} {h['results'][l]['auroc_ci']} (n={h['results'][l]['n']})"
                 if l in h["results"] and "auroc" in h["results"][l] else "—") for h in H.values()) + " |")


def main():
    out = ["# Results (generated by src/make_tables.py from results/*.json)"]
    for ds, dsname in [("borderlines", "BorderLines"), ("mkqa", "MKQA control"), ("pooled", "Pooled BorderLines + MKQA")]:
        out.append(f"\n## {dsname}")
        block(out, ds, "dep_strict", f"{dsname}: primary label (any change across languages)")
        block(out, ds, "dep_claimant", f"{dsname}: secondary label (different claimants named)")
    for t in ["dep_strict", "dep_claimant"]:
        o = J(f"results/flip_overlap_borderlines_{t}.json")
        if o:
            out.append(f"\n## Flip overlap between models (BorderLines, {t})\n")
            out.append("| pair | n | Jaccard | Cohen's κ | agreement | rate A | rate B |\n|---|---|---|---|---|---|---|")
            for k, v in o.items():
                out.append(f"| {k} | {v['n']} | {v['jaccard']} | {v['kappa']} | {v['agreement']} | {v['rate_a']} | {v['rate_b']} |")
        T = J(f"results/transfer_borderlines_{t}.json")
        if T:
            for kind in ["zero_shot", "calibrated"]:
                out.append(f"\n## Transfer, {kind} (BorderLines, {t}); rows = probed model, cols = target model, AUROC [CI]\n")
                out.append("| probed \\ target | " + " | ".join(MODELS) + " |\n|---|---|---|---|")
                for P in MODELS:
                    out.append(f"| {P} | " + " | ".join(cell(T[kind][P].get(Tm)) for Tm in MODELS) + " |")
    Path("results/main_table.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))

    Path("figures").mkdir(exist_ok=True)
    for ds in ["borderlines", "mkqa", "pooled"]:
        targets = [t for t in ["dep_strict", "dep_claimant"] if any(
            Path(f"results/layer_sweep_{m}_{ds}_{t}.json").exists() for m in MODELS)]
        if not targets:
            continue
        fig, axes = plt.subplots(1, len(targets), figsize=(5 * len(targets), 3.6), sharey=True, squeeze=False)
        for ax, t in zip(axes[0], targets):
            for m in MODELS:
                s = J(f"results/layer_sweep_{m}_{ds}_{t}.json")
                if s:
                    n = len(s) - 1
                    ax.plot([x["layer"] / n for x in s], [x["auroc"] for x in s], label=m)
            ax.axhline(0.5, color="grey", lw=0.8, ls="--")
            ax.set_title(f"{ds}: {t}"); ax.set_xlabel("relative depth (layer / #layers)")
        axes[0][0].set_ylabel("AUROC (5-fold grouped CV, C=0.01)"); axes[0][0].legend()
        fig.suptitle("Layer sweep (descriptive; not used for model selection)", fontsize=10)
        fig.tight_layout()
        for ext in ["pdf", "png"]:
            fig.savefig(f"figures/layer_sweep_{ds}.{ext}", dpi=150)
        plt.close(fig)


if __name__ == "__main__":
    main()
